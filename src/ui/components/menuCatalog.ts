/** 界面为未实现条目提供的状态；缺省即「未实现」，菜单项置灰。 */
export interface MenuState {
  run?: () => void;
  checked?: boolean;
  /** 覆盖目录里的默认快捷键文案（例如动态的最近文件）。 */
  hint?: string;
}

export type MenuResolver = (id: string) => MenuState | undefined;

function zhLabel(label: string): string {
  return label === "---" ? label : LABEL_ZH[label] ?? label;
}

function zhSegment(segment: string): string {
  return PATH_ZH[segment] ?? segment;
}

function isSep(entry: MenuEntry): boolean {
  return entry.kind === "sep";
}

/** 去掉首尾与连续分隔线。 */
function tidy(items: MenuEntry[]): MenuEntry[] {
  const out: MenuEntry[] = [];
  for (const item of items) {
    if (isSep(item)) {
      if (out.length === 0 || isSep(out[out.length - 1])) continue;
      out.push(item);
      continue;
    }
    out.push(item);
  }
  while (out.length > 0 && isSep(out[out.length - 1])) out.pop();
  return out;
}

/**
 * 应用已实现状态：无 resolver 的条目置灰。
 *
 * 子菜单本身不置灰 —— 即使整栏都还没实现，也要能展开看到条目名，
 * 不能因为「一个都没做」就把整块菜单藏起来。
 */
function applyState(items: MenuEntry[], resolve: MenuResolver): MenuEntry[] {
  const out: MenuEntry[] = [];
  for (const item of items) {
    if (isSep(item)) {
      out.push(item);
      continue;
    }
    const action = item as MenuAction;
    if (action.children) {
      const children = applyState(action.children, resolve);
      if (children.length === 0) continue;
      action.children = tidy(children);
      if (action.children.length === 0) continue;
      out.push(action);
      continue;
    }
    const state = action.id ? resolve(action.id) : undefined;
    if (state?.run) {
      action.disabled = false;
      action.onSelect = state.run;
    } else {
      action.disabled = true;
      delete action.onSelect;
    }
    if (state?.checked !== undefined) action.checked = state.checked;
    if (state?.hint !== undefined) action.hint = state.hint;
    out.push(action);
  }
  return tidy(out);
}

/** 由 PhotoCraft 的 770 条菜单目录构建 10 个顶级菜单。 */
export function buildMenuGroups(resolve: MenuResolver): MenuGroup[] {
  const children = new Map<string, MenuEntry[]>();
  for (const top of TOP_MENUS) children.set(top.path, []);

  const ensure = (path: string): MenuEntry[] => {
    const found = children.get(path);
    if (found) return found;
    const cut = path.lastIndexOf("/");
    const parent = ensure(path.slice(0, cut));
    const list: MenuEntry[] = [];
    parent.push({ kind: "item", label: zhSegment(path.slice(cut + 1)), children: list });
    children.set(path, list);
    return list;
  };

  for (const [path, label, shortcut, id] of RAW) {
    if (!children.has(path.split("/")[0])) continue;
    const list = ensure(path);
    if (label === "---") {
      list.push({ kind: "sep" });
      continue;
    }
    list.push({
      kind: "item",
      id,
      label: zhLabel(label),
      hint: shortcut || undefined,
    });
  }

  return TOP_MENUS.map((top) => ({
    key: top.key,
    label: top.label,
    items: applyState(children.get(top.path) ?? [], resolve),
  }));
}

/** 深度优先查找菜单项。 */
export function findMenuItem(groups: MenuGroup[], id: string): MenuAction | undefined {
  const walk = (items: MenuEntry[]): MenuAction | undefined => {
    for (const item of items) {
      if (isSep(item)) continue;
      const action = item as MenuAction;
      if (action.id === id) return action;
      if (action.children) {
        const hit = walk(action.children);
        if (hit) return hit;
      }
    }
    return undefined;
  };
  for (const group of groups) {
    const hit = walk(group.items);
    if (hit) return hit;
  }
  return undefined;
}

/** 在指定 id 的条目之后插入若干条目（用于「最近打开」）。 */
export function insertAfterId(
  groups: MenuGroup[],
  afterId: string,
  entries: MenuEntry[],
): boolean {
  const walk = (items: MenuEntry[]): boolean => {
    for (let i = 0; i < items.length; i += 1) {
      const item = items[i];
      if (isSep(item)) continue;
      const action = item as MenuAction;
      if (action.id === afterId) {
        items.splice(i + 1, 0, ...entries);
        return true;
      }
      if (action.children && walk(action.children)) return true;
    }
    return false;
  };
  return groups.some((group) => walk(group.items));
}

/** 在某个顶级菜单末尾追加条目（用于「窗口」的文档列表与帮助菜单）。 */
export function appendToGroup(groups: MenuGroup[], key: string, entries: MenuEntry[]): void {
  const group = groups.find((item) => item.key === key);
  if (group) group.items.push(...entries);
}
